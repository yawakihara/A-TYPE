const ORDER = Object.keys(GLYPHS).join('');
const CELL_W = 6;
const CELL_H = 8;
const atlases = new Map();

/**
 * 指定色のフォントアトラスを生成（キャッシュ）する。
 * @param {string} color CSSカラー
 * @returns {HTMLCanvasElement} アトラス
 */
function atlasFor(color) {
  let c = atlases.get(color);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = ORDER.length * CELL_W;
  c.height = CELL_H;
  const g = c.getContext('2d');
  g.fillStyle = color;
  for (let i = 0; i < ORDER.length; i++) {
    const rows = GLYPHS[ORDER[i]].split('/');
    for (let y = 0; y < rows.length; y++) {
      for (let x = 0; x < rows[y].length; x++) {
        if (rows[y][x] === '#') g.fillRect(i * CELL_W + x, y, 1, 1);
      }
    }
  }
  atlases.set(color, c);
  return c;
}

/**
 * 文字列の描画幅を返す。
 * @param {string} text 文字列
 * @param {number} [scale=1] 拡大率
 * @returns {number} 幅(px)
 */
export function textWidth(text, scale = 1) {
  return Math.max(0, text.length * CELL_W - 1) * scale;
}

/**
 * ビットマップフォントで文字列を描く。小文字は大文字として扱う。
 * @param {CanvasRenderingContext2D} ctx 描画先
 * @param {string} text 文字列
 * @param {number} x 基準X
 * @param {number} y 上端Y
 * @param {string} [color='#fff'] 文字色
 * @param {{scale?:number, align?:'left'|'center'|'right', shadow?:string}} [opt] 拡大率・揃え・影色
 * @returns {void}
 */
export function drawText(ctx, text, x, y, color = '#fff', opt = {}) {
  const scale = opt.scale || 1;
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale);
  let px = Math.round(x);
  if (opt.align === 'center') px = Math.round(x - w / 2);
  else if (opt.align === 'right') px = Math.round(x - w);
  const py = Math.round(y);
  const passes = opt.shadow ? [[opt.shadow, scale, scale], [color, 0, 0]] : [[color, 0, 0]];
  for (const [col, ox, oy] of passes) {
    const atlas = atlasFor(col);
    for (let i = 0; i < str.length; i++) {
      const idx = ORDER.indexOf(str[i]);
      if (idx < 0) continue;
      ctx.drawImage(atlas, idx * CELL_W, 0, 5, 7, px + i * CELL_W * scale + ox, py + oy, 5 * scale, 7 * scale);
    }
  }
}
